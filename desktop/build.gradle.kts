// Headless sanity check for serialization, settings and the audio pipeline.
tasks.register<JavaExec>("selfCheck") {
    group = "verification"
    description = "Runs the headless self-check."
    mainClass.set("dev.gladix.desktop.SelfCheckKt")
    classpath = sourceSets["main"].runtimeClasspath
    // The app targets JVM 21, so the runner must not fall back to whatever
    // java.exe happens to be first on PATH (that used to be a JDK 17 here).
    javaLauncher.set(
        javaToolchains.launcherFor { languageVersion.set(JavaLanguageVersion.of(21)) }
    )
}

// Opens every screen in a real window and exits non-zero if one of them throws.
tasks.register<JavaExec>("uiSmoke") {
    group = "verification"
    description = "Renders every screen once to catch composition errors."
    mainClass.set("dev.gladix.desktop.UiSmokeKt")
    classpath = sourceSets["main"].runtimeClasspath
    jvmArgs = listOf("--enable-native-access=ALL-UNNAMED")
    standardOutput = System.out
    javaLauncher.set(
        javaToolchains.launcherFor { languageVersion.set(JavaLanguageVersion.of(21)) }
    )
}

// Publishes a fake media session so the Windows shell integration can be probed
// from outside (taskbar flyout, media keys).
tasks.register<JavaExec>("mediaProbe") {
    group = "verification"
    description = "Publishes a fake playback session to the Windows media controls."
    mainClass.set("dev.gladix.desktop.SelfCheckKt")
    classpath = sourceSets["main"].runtimeClasspath
    args("media-probe")
    jvmArgs = listOf("--enable-native-access=ALL-UNNAMED")
    standardOutput = System.out
    javaLauncher.set(
        javaToolchains.launcherFor { languageVersion.set(JavaLanguageVersion.of(21)) }
    )
}
